DATA = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    "data", "tests")

PASS = 0
FAIL = 0


def check(name: str, cond: bool, detail: str = "") -> None:
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  PASS {name}")
    else:
        FAIL += 1
        print(f"  FAIL {name} {detail}")


def cells_of(db_path: str) -> dict:
    con = sqlite3.connect(db_path)
    con.row_factory = sqlite3.Row
    out = {}
    for r in con.execute("SELECT * FROM fact_cell_new"):
        out[(r["new_customer"], r["date_key"], r["metric"])] = dict(r)
    con.close()
    return out


def reasons_of(db_path: str) -> set:
    con = sqlite3.connect(db_path)
    rows = {(r[0], r[1], r[2], r[3], r[4]) for r in con.execute(
        "SELECT new_customer,date_key,metric,part,shard_id FROM blocked_reason")}
    con.close()
    return rows


def build_ok(scenario, builder, *args, **kw):
    inp = os.path.join(DATA, scenario + ".db")
    out = os.path.join(DATA, scenario + ".out.db")
    builder(inp, *args, **kw)
    ro = checks.open_input(inp)
    errs = checks.run_all_checks(ro)
    ro.close()
    check(scenario + " input checks clean", errs == [], str(errs))
    engine.build(inp, out)
    return inp, out


def test_atomic_split() -> None:
    print("[1] atomic split then merge (headline)")
    _, out = build_ok("atomic_split", scenarios.build_atomic_split)
    c = cells_of(out)
    # Hand-written from the scenario: a=10 ticket T -> P, b=20 ticket T -> Q
    check("split P sum=10", c[("P", "2026-01-01", "sales")]["sum_amount"] == 10)
    check("split Q sum=20", c[("Q", "2026-01-01", "sales")]["sum_amount"] == 20)
    check("split P distinct=1",
          c[("P", "2026-01-01", "sales")]["distinct_ticket"] == 1)
    check("split Q distinct=1",
          c[("Q", "2026-01-01", "sales")]["distinct_ticket"] == 1)
    check("split P min/cnt",
          c[("P", "2026-01-01", "sales")]["min_amount"] == 10
          and c[("P", "2026-01-01", "sales")]["cnt_nonnull"] == 1)
    check("split statuses rebuilt",
          all(v["agg_status"] == "rebuilt" and
              v["distinct_status"] == "rebuilt" for v in c.values()))

    _, outm = build_ok("atomic_merge", scenarios.build_atomic_merge)
    cm = cells_of(outm)
    r = cm[("R", "2026-01-01", "sales")]
    check("merge sum=30", r["sum_amount"] == 30)
    check("merge distinct=1 (same ticket once)", r["distinct_ticket"] == 1)
    check("merge cnt=2 min=10", r["cnt_nonnull"] == 2 and r["min_amount"] == 10)
    _cross_check("atomic_split")
    _cross_check("atomic_merge")


def test_oldsum_split_blocked() -> None:
    print("[2] old-summary only: split must block, never 15/15")
    _, out = build_ok("oldsum_split", scenarios.build_oldsum_split)
    c = cells_of(out)
    for cust in ("P", "Q"):
        cell = c[(cust, "2026-01-01", "sales")]
        check(f"{cust} agg blocked", cell["agg_status"] == "blocked")
        check(f"{cust} distinct blocked", cell["distinct_status"] == "blocked")
        check(f"{cust} no invented 15",
              cell["sum_amount"] is None and cell["min_amount"] is None
              and cell["cnt_nonnull"] is None)
    # Explicitly assert the forbidden per-head split never appears.
    check("no 15/15 anywhere",
          all(v["sum_amount"] != 15 for v in c.values()))
    r = reasons_of(out)
    check("blocked reasons name shard and part",
          any(x[3] == "agg" and x[4] == "sh_old" for x in r)
          and any(x[3] == "distinct" and x[4] == "sh_old" for x in r))
    _cross_check("oldsum_split")


def test_cd_merge() -> None:
    print("[3] C+D merge: sum usable, distinct blocked then recovered")
    _, out_no = build_ok("cd_noset", scenarios.build_cd_merge,
                         with_sets=False)
    c = cells_of(out_no)
    m = c[("M", "2026-01-01", "sales")]
    check("merged sum=10 usable", m["sum_amount"] == 10)
    check("merged cnt=2 min=5", m["cnt_nonnull"] == 2 and m["min_amount"] == 5)
    check("distinct blocked without sets",
          m["distinct_status"] == "blocked" and m["distinct_ticket"] is None)
    check("agg carried", m["agg_status"] == "carried")

    _, out_set = build_ok("cd_set", scenarios.build_cd_merge,
                          with_sets=True)
    ms = cells_of(out_set)[("M", "2026-01-01", "sales")]
    check("distinct rebuilt=1 with both sets {X}",
          ms["distinct_ticket"] == 1 and ms["distinct_status"] == "rebuilt")
    check("sum still 10 with sets", ms["sum_amount"] == 10)
    _cross_check("cd_noset")
    _cross_check("cd_set")


def test_ambiguity_proof() -> None:
    print("[4] same old summary, two raw datasets -> different split truth")
    # Build the two raw datasets and confirm their engine answers differ.
    _, out1 = build_ok("ambig_v1", scenarios.build_ambiguous_raw, variant=1)
    _, out2 = build_ok("ambig_v2", scenarios.build_ambiguous_raw, variant=2)
    c1 = cells_of(out1)
    c2 = cells_of(out2)
    p1 = c1[("P", "2026-01-01", "sales")]["sum_amount"]
    p2 = c2[("P", "2026-01-01", "sales")]["sum_amount"]
    check("raw v1 P sum=10", p1 == 10)
    check("raw v2 P sum=20", p2 == 20)
    check("raw answers differ (10 vs 20)", p1 != p2)

    # Independently derive the OLD summary that both datasets collapse to.
    # This is computed here from the raw rows, not from the engine.
    derived = {}
    for variant in (1, 2):
        inp = os.path.join(DATA, f"ambig_v{variant}.db")
        con = sqlite3.connect(inp)
        total = con.execute(
            "SELECT SUM(amount), COUNT(amount), MIN(amount) FROM atomic_fact"
        ).fetchone()
        members = sorted((r[0], r[1]) for r in con.execute(
            "SELECT DISTINCT src_source, member_id FROM atomic_fact"))
        con.close()
        derived[variant] = {"sum": total[0], "cnt": total[1],
                            "min": total[2], "members": members}
        check(f"v{variant} old summary sum=30 members a,b",
              derived[variant]["sum"] == 30 and len(members) == 2)
    check("both raw datasets share the identical old summary",
          derived[1] == derived[2])
    # The old-summary-only representation cannot distinguish them, which is
    # exactly why the split is blocked in scenario [2].
    print("    => identical retained summary {sum:30, cnt:2, min:10,"
          " members:[a,b]} but true split sums are 10/20 vs 20/10:"
          " the customer-grain summary is insufficient")


