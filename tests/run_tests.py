def test_partial_blocked() -> None:
    print("[7] partial shard computable but whole cell blocked")
    _, out = build_ok("partial", edge_cases.build_partial_blocked)
    c = cells_of(out)
    p = c[("P", "2026-05-01", "sales")]
    check("P cell blocked despite computable atomic 9",
          p["agg_status"] == "blocked" and p["sum_amount"] is None)
    # The recoverable atomic contribution must still be visible, not dropped.
    con = sqlite3.connect(out)
    kinds = {r[0] for r in con.execute(
        "SELECT DISTINCT lineage_kind FROM cell_lineage "
        "WHERE new_customer='P' AND metric='sales'")}
    has_atomic = con.execute(
        "SELECT 1 FROM cell_lineage WHERE new_customer='P' "
        "AND lineage_kind='atomic' AND amount=9").fetchone() is not None
    con.close()
    check("recoverable atomic contribution kept in lineage", has_atomic)
    check("both atomic and old_block trail present",
          "atomic" in kinds and "old_block" in kinds)


