    os.makedirs(DATA, exist_ok=True)
    for fn in (
        test_atomic_split,
        test_oldsum_split_blocked,
        test_cd_merge,
        test_ambiguity_proof,
        test_null_empty_equalfacts,
        test_cross_source,
        test_partial_blocked,
        test_full_summary,
        test_overlap_fails_clean,
        test_input_order_invariance,
        test_large_spill,
        test_preview_and_explain,
        test_input_untouched_and_persistence,
        test_integer_no_float,
    ):
        fn()
    print(f"\n{FAIL} failures, {PASS} assertions passed")
    return 1 if FAIL else 0


