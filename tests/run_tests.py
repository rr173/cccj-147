def test_input_untouched_and_persistence() -> None:
    print("[13] input read-only, old results unchanged, new process reads")
    inp = os.path.join(DATA, "atomic_split.db")
    out = os.path.join(DATA, "atomic_split.out.db")
    before = engine._sha256_file(inp)
    engine.build(inp, os.path.join(DATA, "again.out.db"))
    after = engine._sha256_file(inp)
    check("input file hash unchanged", before == after)
    check("previous output not overwritten by second build",
          os.path.exists(out))
    # A brand new connection (simulating a new process) reads the result.
    con = sqlite3.connect(out)
    meta = dict(con.execute("SELECT key,value FROM run_meta"))
    n_cells = con.execute("SELECT COUNT(*) FROM fact_cell_new").fetchone()[0]
    versions = (con.execute(
        "SELECT value FROM run_meta WHERE key='mapping_old_version'")
        .fetchone()[0],
        con.execute(
        "SELECT value FROM run_meta WHERE key='mapping_new_version'")
        .fetchone()[0])
    con.close()
    check("both mapping versions persisted", versions == ("v0", "v1"))
    check("result readable in a fresh connection", n_cells == 2)
    check("status=complete recorded", meta.get("status") == "complete")


