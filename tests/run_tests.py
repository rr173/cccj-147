def _cross_check(scenario: str) -> None:
    inp = os.path.join(DATA, scenario + ".db")
    out = os.path.join(DATA, scenario + ".out.db")
    expected = naive_rekey(inp)
    actual = cells_of(out)
    ok = True
    detail = ""
    if set(expected) != set(actual):
        ok = False
        detail = f"keys differ {set(expected) ^ set(actual)}"
    for k, exp in expected.items():
        act = actual.get(k)
        if act is None:
            ok = False
            break
        for f in ("sum_amount", "cnt_nonnull", "min_amount",
                  "distinct_ticket", "distinct_status"):
            if exp[f] != act[f]:
                ok = False
                detail = f"{k} {f}: naive={exp[f]} engine={act[f]}"
    # agg_status: oracle only says rebuilt/blocked; engine may say carried.
    for k, exp in expected.items():
        if exp["agg_status"] == "blocked" and actual[k]["agg_status"] != "blocked":
            ok = False
            detail = f"{k} blocked mismatch"
    check(f"naive oracle agrees on {scenario}", ok, detail)


